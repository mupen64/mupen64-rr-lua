#pragma once

#include <Common.Views/IDialogService.hpp>
#include <lua/LuaRealmManager.hpp>

namespace LuaCore::Dialogs
{
static int show_notification(lua_State *L)
{
    static const char *const types[] = {"error", "warn", "info", nullptr};
    static constexpr CoreMessageTone tones[] = {CoreMessageTone::Error, CoreMessageTone::Warn, CoreMessageTone::Info};

    const auto type = luaL_checkoption(L, 3, "warn", types);
    luaL_checkstring(L, 1);
    if (!lua_isnoneornil(L, 2))
    {
        luaL_checkstring(L, 2);
    }

    const auto content = luaL_checkstlstring(L, 1);
    std::optional<std::string> title;
    if (!lua_isnoneornil(L, 2))
    {
        title = luaL_checkstlstring(L, 2);
    }

    DialogService::show_notification(content, title, tones[type], "This notification was generated by a Lua script.");
    return 0;
}
} // namespace LuaCore::Dialogs
